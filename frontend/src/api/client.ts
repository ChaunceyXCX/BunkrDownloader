function toAuthRes(s: Bindings.Session): AuthRes {
  const quota = toQuota(s.quota)
  return { user: toUser(s.user, quota), token: nullable(s.token) ?? undefined, quota }
}

/* ------------------------------------------------------------------ *
 * §2 Auth
 * ------------------------------------------------------------------ */
export const authApi = {
  register: async (body: RegisterReq): Promise<AuthRes> =>
    toAuthRes(await call(AuthService.Register(body.username, body.email, body.password), { label: 'register' })),
  login: async (body: LoginReq): Promise<AuthRes> =>
    toAuthRes(await call(AuthService.Login(body.account, body.password), { label: 'login' })),
  /** Best-effort: the local session is dropped by the caller either way. */
  logout: async (): Promise<OkRes> => {
    try {
      await AuthService.Logout(token())
    } catch {
      /* no host / service gone — the token is discarded regardless */
    }
    return { ok: true }
  },
  /** Silent: a 401 here is the normal "session expired" path, not a toast. */
  me: async (): Promise<AuthRes> =>
    toAuthRes(await call(AuthService.Me(token()), { quiet: true, label: 'me' })),
  changePassword: async (body: ChangePasswordReq): Promise<OkRes> => {
    await call(
      AuthService.ChangePassword(token(), body.old_password, body.new_password),
      { label: 'changePassword' },
    )
    return { ok: true }
  },
}

