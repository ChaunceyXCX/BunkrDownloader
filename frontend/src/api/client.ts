/**
 * Transport for the desktop build.
 *
 * Every call goes through the Wails v3 service bindings generated by
 * `wails3 generate bindings`; there is no HTTP and no WebSocket. The service
 * methods return `[value, error]` pairs, so this module keeps the *public*
 * surface of the previous REST client (`authApi`, `membershipApi`, `tasksApi`,
 * `systemApi` + the envelopes in `types.ts`) and adapts the Go models to it.
 * The stores and views are therefore untouched.
 */

/** Kept for import compatibility — no request is ever built from it. */
export const API_BASE = '@wails'

export const TOKEN_KEY = 'bunkr_token'

/** Typed error thrown by every failed service call. */
export class ApiError extends Error {
  readonly status: number
  readonly code: string
  readonly details?: Record<string, unknown>

  constructor(status: number, code: string, message: string, details?: Record<string, unknown>) {
    super(message)
    this.name = 'ApiError'
    this.status = status
    this.code = code
    this.details = details
  }

  /** True when the session is gone / invalid. */
  get isUnauthorized(): boolean {
    return this.status === 401
  }
}

/**
 * The bindings only carry `code` + `message`, while the app still reads
 * `ApiError.status` (toasts, 404/403 handling in the task store). Map the
 * documented error codes onto the HTTP status they used to carry.
 */
const STATUS_BY_CODE: Record<string, number> = {
  bad_request: 400,
  invalid_url: 400,
  weak_password: 400,
  invalid_code: 400,
  email_taken: 409,
  username_taken: 409,
  invalid_credentials: 401,
  unauthorized: 401,
  forbidden: 403,
  not_found: 404,
  conflict: 409,
  invalid_state: 409,
  quota_exceeded: 429,
  too_many_requests: 429,
  internal_error: 500,
  upstream_error: 502,
  aria2_unavailable: 503,
  network_error: 0,
}

function statusForCode(code: string): number {
  const mapped = STATUS_BY_CODE[code]
  return mapped === undefined ? 500 : mapped
}

/* ------------------------------------------------------------------ *
 * Token + 401 plumbing
 * ------------------------------------------------------------------ */
type UnauthorizedHandler = () => void
let onUnauthorized: UnauthorizedHandler | null = null
let onGlobalError: ((err: ApiError) => void) | null = null

export function onUnauthorizedHandler(fn: UnauthorizedHandler): void {
  onUnauthorized = fn
}
export function onGlobalErrorHandler(fn: (err: ApiError) => void): void {
  onGlobalError = fn
}

export function getToken(): string | null {
  try {
    return localStorage.getItem(TOKEN_KEY)
  } catch {
    return null
  }
}

export function setToken(token: string | null): void {
  try {
    if (token) localStorage.setItem(TOKEN_KEY, token)
    else localStorage.removeItem(TOKEN_KEY)
  } catch {
    /* storage unavailable (private mode) — session stays in-memory only */
  }
}

/** Kept for import compatibility — nothing builds URLs any more. */
export function apiUrl(path: string): string {
  return `${API_BASE}/${path.startsWith('/') ? path.slice(1) : path}`
}

function token(): string {
  return getToken() ?? ''
}

/* ------------------------------------------------------------------ *
 * Call plumbing
 * ------------------------------------------------------------------ */
type Pair<T> = [T | null, Bindings.APIError | null]

interface CallOptions {
  /** Suppress the global error toast (the caller handles it). */
  quiet?: boolean
  /** Label used when a method answers `nil, nil` (should not happen). */
  label?: string
}

function toApiError(err: Bindings.APIError): ApiError {
  const code = err.code || 'internal_error'
  return new ApiError(statusForCode(code), code, err.message || 'Request Failed', err.details)
}

function report(err: ApiError, quiet: boolean): ApiError {
  if (err.isUnauthorized) {
    setToken(null)
    onUnauthorized?.()
  } else if (!quiet) {
    onGlobalError?.(err)
  }
  return err
}

/** Unwraps a `[value, error]` service result into a value or a thrown ApiError. */
async function call<T>(invoke: CancellablePromise<Pair<T>>, opts: CallOptions = {}): Promise<T> {
  const { quiet = false, label = 'service' } = opts
  let result: Pair<T>
  try {
    result = await invoke
  } catch (e) {
    // No Wails host, cancelled call, wrong argument count, … — keep the single
    // failure shape the app already handles.
    throw report(new ApiError(0, 'network_error', (e as Error)?.message || 'Request Failed'), quiet)
  }
  const [value, apiError] = result
  if (apiError) throw report(toApiError(apiError), quiet)
  if (value === null || value === undefined) {
    throw report(new ApiError(500, 'internal_error', `${label} 返回空结果`), quiet)
  }
  return value
}

/** Same, for the few service methods that answer with a bare value. */
async function callValue<T>(invoke: CancellablePromise<T | null>, opts: CallOptions = {}): Promise<T> {
  const { quiet = false, label = 'service' } = opts
  let value: T | null
  try {
    value = await invoke
  } catch (e) {
    throw report(new ApiError(0, 'network_error', (e as Error)?.message || 'Request Failed'), quiet)
  }
  if (value === null || value === undefined) {
    throw report(new ApiError(500, 'internal_error', `${label} 返回空结果`), quiet)
  }
  return value
}

/* ------------------------------------------------------------------ *
 * Model adapters — Go structs → types.ts envelopes
 * ------------------------------------------------------------------ */
function compact<T>(list: readonly (T | null)[] | null | undefined): T[] {
  return (list ?? []).filter((item): item is T => item !== null && item !== undefined)
}

/** Go sends `""` / an omitted field where the API contract declares `null`. */
function nullable(value: string | null | undefined): string | null {
  return value ? value : null
}

function toQuota(q: Store.Quota | null | undefined): Quota {
  if (!q) {
    return {
      plan: 'free',
      is_member: false,
      links_used: 0,
      links_limit: 0,
      links_unlimited: false,
      files_used: 0,
      files_limit: 0,
      files_unlimited: false,
      concurrent_limit: 0,
      concurrent_running: 0,
    }
  }
  return {
    plan: q.plan as Quota['plan'],
    is_member: q.is_member,
    links_used: q.links_used,
    links_limit: q.links_limit,
    links_unlimited: q.links_unlimited,
    files_used: q.files_used,
    files_limit: q.files_limit,
    files_unlimited: q.files_unlimited,
    concurrent_limit: q.concurrent_limit,
    concurrent_running: q.concurrent_running,
  }
}

/** `store.User` has no `is_member` field, so it is derived from the quota. */
function toUser(u: Store.User | null | undefined, quota?: Quota | null): User {
  if (!u) {
    return {
      id: 0,
      username: '',
      email: '',
      role: 'user',
      plan: 'free',
      plan_expires_at: null,
      is_member: false,
      created_at: '',
    }
  }
  return {
    id: u.id,
    username: u.username,
    email: u.email,
    role: u.role as User['role'],
    plan: u.plan as User['plan'],
    plan_expires_at: nullable(u.plan_expires_at),
    is_member: quota ? quota.is_member : u.plan === 'member',
    created_at: u.created_at,
  }
}

