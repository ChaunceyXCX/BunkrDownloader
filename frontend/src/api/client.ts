export type TaskActionResponse = TaskActionRes & { retried?: number }

export const tasksApi = {
  list: async (q?: ListTasksQuery): Promise<ListTasksRes> => {
    const res = await call(
      TaskService.ListTasks(
        token(),
        q?.status ?? '',
        q?.q ?? '',
        q?.sort ?? '',
        q?.order ?? '',
        q?.limit ?? 50,
        q?.offset ?? 0,
      ),
      { label: 'listTasks' },
    )
    return { tasks: compact(res.tasks).map(toTask), total: res.total }
  },
  create: async (body: CreateTaskReq): Promise<CreateTaskRes> => {
    const res = await call(
      TaskService.CreateTask(token(), {
        url: body.url,
        urls: [],
        options: toTaskOptionsInput(body.options),
        auto_start: body.auto_start,
      }),
      { label: 'createTask' },
    )
    return { task_ids: res.task_ids ?? [], count: res.count, quota: toQuota(res.quota) }
  },
  detail: async (id: number): Promise<TaskDetailRes> => {
    const res = await call(TaskService.GetTask(token(), id), { label: 'taskDetail' })
    const task = toTask(res.task)
    // The web endpoint mirrored the task as `stats`; the binding returns the
    // per-status file summary instead.
    return { task, stats: task, files_summary: res.files_summary ?? {} }
  },
  remove: async (id: number): Promise<DeleteTaskRes> => {
    await call(TaskService.DeleteTask(token(), id), { label: 'deleteTask' })
    return { ok: true, deleted: id }
  },
  action: async (
    id: number,
    act: 'start' | 'pause' | 'resume' | 'cancel' | 'retry',
    body?: TaskActionReq,
  ): Promise<TaskActionResponse> => {
    if (act === 'retry') {
      const retried = await call(TaskService.Retry(token(), id, body?.files ?? []), { label: 'retryTask' })
      // Retry answers with the number of re-queued files, so the refreshed task
      // is read back for the store to replace.
      const detail = await call(TaskService.GetTask(token(), id), { label: 'taskDetail' })
      return { ok: true, retried, task: toTask(detail.task) }
    }
    const invoke =
      act === 'start'
        ? TaskService.Start(token(), id)
        : act === 'pause'
          ? TaskService.Pause(token(), id)
          : act === 'resume'
            ? TaskService.Resume(token(), id)
            : TaskService.Cancel(token(), id)
    return { ok: true, task: toTask(await call(invoke, { label: `task:${act}` })) }
  },
  files: async (id: number, q?: ListFilesQuery): Promise<ListFilesRes> => {
    const res = await call(
      TaskService.ListFiles(
        token(),
        id,
        q?.status ?? '',
        q?.q ?? '',
        q?.sort ?? '',
        q?.order ?? '',
        q?.limit ?? 50,
        q?.offset ?? 0,
      ),
      { label: 'listFiles' },
    )
    return {
      files: compact(res.files).map(toFile),
      total: res.total,
      limit: res.limit,
      offset: res.offset,
    }
  },
  retryFile: async (id: number, fileId: number): Promise<FileActionRes> => ({
    ok: true,
    file: toFile(await call(TaskService.RetryFile(token(), id, fileId), { label: 'retryFile' })),
  }),
  events: async (id: number, q?: ListEventsQuery): Promise<ListEventsRes> => {
    const res = await call(
      TaskService.ListEvents(token(), id, q?.before_id ?? 0, q?.limit ?? 200),
      { label: 'listEvents' },
    )
    return { events: compact(res.events).map(toEvent) }
  },
  recentEvents: async (limit = 50): Promise<ListEventsRes> => {
    const res = await call(TaskService.ListEvents(token(), 0, 0, limit), { label: 'recentEvents' })
    return { events: compact(res.events).map(toEvent) }
  },
}

