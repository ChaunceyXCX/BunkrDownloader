export const membershipApi = {
  plans: async (): Promise<PlansRes> => {
    const res = await callValue(MembershipService.Plans(), { label: 'plans' })
    return { plans: compact(res.plans).map(toPlan) }
  },
  status: async (): Promise<MembershipStatusRes> => {
    const s = await call(MembershipService.Status(token()), { label: 'membershipStatus' })
    return {
      plan: (s.plan || 'free') as PlanId,
      is_member: s.is_member,
      expires_at: nullable(s.expires_at),
      quota: toQuota(s.quota),
    }
  },
  createOrder: async (body: CreateOrderReq): Promise<CreateOrderRes> => ({
    order: toOrder(await call(MembershipService.CreateOrder(token(), body.plan), { label: 'createOrder' })),
  }),
  orders: async (): Promise<ListOrdersRes> => {
    const res = await call(MembershipService.ListOrders(token()), { label: 'orders' })
    return { orders: compact(res.orders).map(toOrder) }
  },
  pay: async (id: number, body: PayOrderReq): Promise<PayOrderRes> => {
    const res = await call(
      MembershipService.PayOrder(token(), id, body?.pay_method ?? 'alipay'),
      { label: 'payOrder' },
    )
    const quota = toQuota(res.quota)
    return { order: toOrder(res.order), user: toUser(res.user, quota), quota }
  },
  cancelOrder: async (body: CancelOrderReq): Promise<CancelOrderRes> => ({
    order: toOrder(await call(MembershipService.CancelOrder(token(), body.order_id), { label: 'cancelOrder' })),
  }),
  redeem: async (body: RedeemReq): Promise<RedeemRes> => {
    const session = await call(MembershipService.Redeem(token(), body.code), { label: 'redeem' })
    const quota = toQuota(session.quota)
    return { user: toUser(session.user, quota), quota }
  },
}

